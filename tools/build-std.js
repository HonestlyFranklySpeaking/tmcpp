#!/usr/bin/env node
// Bundle library/std/*.tmcpp into src/std/index.js, the built-in libraries (import "std/ui").
// library/std is the source of truth; run this after editing it (build-ext runs it too).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../library/std/", import.meta.url);
const std = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".tmcpp")).sort()) {
  std[`std/${f.replace(/\.tmcpp$/, "")}`] = readFileSync(new URL(f, dir), "utf8").replace(/\r\n/g, "\n");
}
const out = `// Generated by tools/build-std.js from library/std/*.tmcpp. Don't edit: edit those files and rebuild.
export const STD = ${JSON.stringify(std, null, 2)};
`;
writeFileSync(new URL("../src/std/index.js", import.meta.url), out);
console.log(`built src/std/index.js: ${Object.keys(std).join(", ")}`);
